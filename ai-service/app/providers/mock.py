"""
Mock providers for local development and CI testing.
These should NEVER be used in production (MOCK_AI must be false).
"""
import logging
from typing import List, Optional

from app.providers.interfaces import (
    EmbeddingProvider,
    EmbeddingResponse,
    LLMProvider,
    LLMResponse,
)

logger = logging.getLogger(__name__)

# 768-dim zero vector (matches gemini-embedding-001 dimensions)
_MOCK_EMBEDDING = [0.0] * 768


class MockLLMProvider(LLMProvider):
    @property
    def name(self) -> str:
        return "mock"

    @property
    def model(self) -> str:
        return "mock-llm"

    async def generate(
        self,
        prompt: str,
        system: Optional[str] = None,
        max_tokens: int = 1024,
        temperature: float = 0.2,
    ) -> LLMResponse:
        logger.debug("MockLLM.generate called (dev only)")
        return LLMResponse(
            text=(
                "[MOCK RESPONSE — development only] "
                "This answer is generated by the mock provider. "
                "Set MOCK_AI=false and configure a real provider for production."
            ),
            input_tokens=len(prompt) // 4,
            output_tokens=50,
            provider="mock",
            model="mock-llm",
        )

    async def health(self) -> bool:
        return True


class MockEmbeddingProvider(EmbeddingProvider):
    @property
    def name(self) -> str:
        return "mock"

    @property
    def model(self) -> str:
        return "mock-embedding"

    @property
    def dimensions(self) -> int:
        return 768

    async def embed(self, text: str) -> EmbeddingResponse:
        logger.debug("MockEmbedding.embed called (dev only)")
        return EmbeddingResponse(
            embedding=_MOCK_EMBEDDING.copy(),
            dimensions=768,
            provider="mock",
            model="mock-embedding",
        )

    async def embed_batch(self, texts: List[str]) -> List[EmbeddingResponse]:
        return [
            EmbeddingResponse(
                embedding=_MOCK_EMBEDDING.copy(),
                dimensions=768,
                provider="mock",
                model="mock-embedding",
            )
            for _ in texts
        ]

    async def health(self) -> bool:
        return True
